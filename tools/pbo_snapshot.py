#!/usr/bin/env python3
"""Reproduce the headline PBO figure from a committed price snapshot.

WHY THIS EXISTS
The research page runs CPCV on a rolling window of freshly fetched prices, so
its PBO is a statement about whatever window it ran on: two runs of identical
code on SPY reported 63% and 72%. That instability is documented as a finding,
but it also meant the headline figure could not be regenerated by anyone,
because the window it came from was gone. This pins one dated window: the
closes are committed as a CSV and the figure is recomputed from that file with
the same code the live endpoint uses (cpcv.cpcv_from_prices).

Yahoo's adjusted closes are themselves revised as later dividends are paid, so
re-downloading the "same" dates is not the same data. The CSV is the data.

USAGE
    python tools/pbo_snapshot.py            # recompute from the committed CSV
    python tools/pbo_snapshot.py --fetch    # re-download the window first (changes the data)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

import cpcv  # noqa: E402
import features  # noqa: E402

TICKER = "SPY"
START, END = "2021-08-02", "2026-07-31"   # the five years before the 2026-08-01 run
CSV = ROOT / "docs" / "data" / f"{TICKER}_close_{START}_{END}.csv"
OUT = ROOT / "docs" / "data" / "pbo_snapshot.json"


def fetch() -> None:
    # yfinance treats `end` as exclusive, so ask for the day after.
    end_excl = (pd.Timestamp(END) + pd.Timedelta(days=1)).strftime("%Y-%m-%d")
    df = features.fetch_ohlcv(TICKER, start=START, end=end_excl)
    if df is None or df.empty:
        sys.exit(f"could not download {TICKER}")
    CSV.parent.mkdir(parents=True, exist_ok=True)
    out = df[["Close"]].copy()
    out.index = pd.to_datetime(out.index).tz_localize(None).date
    out.index.name = "Date"
    # LF on every OS: the snapshot records this file's SHA-256 (.gitattributes agrees).
    out.to_csv(CSV, float_format="%.6f", lineterminator="\n")
    print(f"wrote {CSV.relative_to(ROOT)} ({len(out)} rows)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--fetch", action="store_true", help="re-download the window first")
    args = ap.parse_args()
    if args.fetch or not CSV.exists():
        fetch()

    close = pd.read_csv(CSV, index_col="Date", parse_dates=True)["Close"]
    res = cpcv.cpcv_from_prices(close, TICKER, n_groups=10, embargo=5)
    if not res.get("available"):
        sys.exit(res.get("reason", "CPCV unavailable"))

    deg = res["degradation"]
    retention = deg["median_oos_sr"] / deg["median_is_sr"] if deg["median_is_sr"] else 0.0
    snapshot = {
        "ticker": TICKER,
        "window": {"start": START, "end": END, "rows": len(close)},
        "data": {"file": str(CSV.relative_to(ROOT)).replace("\\", "/"),
                 "sha256": hashlib.sha256(CSV.read_bytes()).hexdigest()},
        "settings": {"n_strategies": res["n_strategies"], "n_groups": res["n_groups"],
                     "n_splits": res["n_combos"], "rows_after_warmup": res["n_rows"],
                     "embargo": res["embargo"]},
        "pbo": res["pbo"],
        "median_is_sharpe": deg["median_is_sr"],
        "median_oos_sharpe": deg["median_oos_sr"],
        "sharpe_retention": round(retention, 4),
        "degradation_slope": deg["slope"],
        "prob_oos_loss": res["prob_oos_loss"],
        "generated_by": "python tools/pbo_snapshot.py",
    }
    OUT.write_text(json.dumps(snapshot, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: snapshot[k] for k in ("window", "settings", "pbo", "median_is_sharpe",
                                                "median_oos_sharpe", "sharpe_retention",
                                                "degradation_slope", "prob_oos_loss")}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
